def main():
    out = {}
    total = 0
    for ticker, rows in RAW.items():
        rows_sorted = sorted(rows, key=lambda r: r[0])
        out[ticker] = [{"ts_utc": ts, "direction": direction, "price": price} for ts, direction, price in rows_sorted]
        total += len(rows_sorted)

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tradingview_1h_cross_alerts.json")
    with open(out_path, "w") as f:
        json.dump(out, f, indent=2)

    zero = [t for t, rows in RAW.items() if not rows]
    print("Wrote " + out_path + ": " + str(total) + " alerts, " + str(len(zero)) + " tickers with zero")
    dates = [r[0] for rows in RAW.values() for r in rows]
    print("Date range: " + min(dates) + " to " + max(dates))


if __name__ == "__main__":
    main()
